"""Regenerate database/seed_data.sql from app/demo_data.py.

Run from the backend folder:  python scripts/export_seed_sql.py

It builds the demo data in a temporary SQLite database, then writes INSERT
statements in which every date is RELATIVE to the day the SQL is loaded
(DATE_SUB(CURDATE(), INTERVAL n DAY)), so the demo history never goes stale.
"""
import os
import sys
import warnings
from datetime import date, datetime
from decimal import Decimal
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
warnings.filterwarnings("ignore")
os.environ["TEST_DATABASE_URL"] = "sqlite:///:memory:"

from app import create_app  # noqa: E402
from app.config import TestingConfig  # noqa: E402
from app.demo_data import DEMO_EMAIL, DEMO_PASSWORD, seed  # noqa: E402
from app.extensions import db  # noqa: E402

TABLES = ["users", "households", "grocery_items", "inventory", "consumption", "purchases"]
OUTPUT = Path(__file__).resolve().parents[2] / "database" / "seed_data.sql"


def sql_value(value, today):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, datetime):
        return "NOW()"
    if isinstance(value, date):
        return f"DATE_SUB(CURDATE(), INTERVAL {(today - value).days} DAY)"
    if isinstance(value, (int, float, Decimal)):
        return str(value)
    return "'" + str(value).replace("\\", "\\\\").replace("'", "''") + "'"


def main():
    app = create_app(TestingConfig)
    today = date.today()
    with app.app_context():
        db.create_all()
        seed()
        lines = [
            "-- =====================================================================",
            "-- DEMONSTRATION DATA ONLY — not a real household's history.",
            f"-- Demo login: {DEMO_EMAIL} / {DEMO_PASSWORD}",
            "-- Generated by backend/scripts/export_seed_sql.py from app/demo_data.py.",
            "-- Dates are relative to the day you load this file, so the demo stays current.",
            "-- Load AFTER schema.sql into an EMPTY database (ids start at 1).",
            "-- Easier alternative:  flask seed-demo",
            "-- =====================================================================",
            "",
            "SET FOREIGN_KEY_CHECKS = 0;",
            "START TRANSACTION;",
        ]
        for table_name in TABLES:
            table = db.metadata.tables[table_name]
            rows = db.session.execute(table.select().order_by(table.c.id)).mappings().all()
            columns = [c.name for c in table.columns]
            lines.append(f"\n-- {table_name} ({len(rows)} rows)")
            for row in rows:
                values = ", ".join(sql_value(row[c], today) for c in columns)
                lines.append(f"INSERT INTO `{table_name}` ({', '.join(f'`{c}`' for c in columns)}) VALUES ({values});")
        lines += ["", "COMMIT;", "SET FOREIGN_KEY_CHECKS = 1;", ""]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
