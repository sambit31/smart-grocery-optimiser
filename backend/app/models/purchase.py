from app.extensions import db
from app.models.user import utc_now
from app.utils.numbers import to_float


class Purchase(db.Model):
    __tablename__ = "purchases"
    __table_args__ = (
        db.UniqueConstraint("household_id", "client_reference", name="uq_purchase_client_reference"),
        db.Index("ix_purchases_household_date", "household_id", "purchase_date"),
    )

    id = db.Column(db.Integer, primary_key=True)
    household_id = db.Column(db.Integer, db.ForeignKey("households.id", ondelete="CASCADE"), nullable=False)
    item_id = db.Column(db.Integer, db.ForeignKey("grocery_items.id"), nullable=False, index=True)
    quantity = db.Column(db.Numeric(12, 3), nullable=False)
    unit_price = db.Column(db.Numeric(10, 2), nullable=False)
    total_price = db.Column(db.Numeric(12, 2), nullable=False)
    purchase_date = db.Column(db.Date, nullable=False)
    store_name = db.Column(db.String(120))
    notes = db.Column(db.String(500))
    # True when this purchase added its quantity to inventory.
    applied_to_inventory = db.Column(db.Boolean, nullable=False, default=True)
    # Random id generated by the form; the unique constraint stops a double
    # click / network retry from recording (and stocking) the same purchase twice.
    client_reference = db.Column(db.String(64))
    # Set when the purchase came from a shopping-list item ("mark purchased").
    recommendation_item_id = db.Column(
        db.Integer, db.ForeignKey("recommendation_items.id", ondelete="SET NULL"), unique=True
    )
    created_at = db.Column(db.DateTime, nullable=False, default=utc_now)

    item = db.relationship("GroceryItem")

    def to_dict(self):
        return {
            "id": self.id,
            "item_id": self.item_id,
            "item_name": self.item.name,
            "category": self.item.category,
            "unit": self.item.unit,
            "quantity": to_float(self.quantity),
            "unit_price": to_float(self.unit_price),
            "total_price": to_float(self.total_price),
            "purchase_date": self.purchase_date.isoformat(),
            "store_name": self.store_name,
            "notes": self.notes,
            "applied_to_inventory": self.applied_to_inventory,
            "recommendation_item_id": self.recommendation_item_id,
            "created_at": self.created_at.isoformat(),
        }
